package io.github.ranjandas.kimono.core.design.theme

import androidx.compose.ui.unit.dp

/**
 * The spacing scale, in 4 dp steps (#127). Gaps, insets and padding come from here, so the screens share one rhythm
 * rather than a mix of near-equal values.
 */
object KimonoSpacing {
    val XS = 4.dp
    val S = 8.dp
    val M = 12.dp
    val L = 16.dp
    val XL = 20.dp
    val XXL = 24.dp
    val XXXL = 32.dp
}
